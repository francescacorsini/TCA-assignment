import ComposableArchitecture

/// The root feature of the application.
///
/// `AppFeature` includes the root Reducer, composes the individual screen features and owns stack-based
/// navigation.
/// Child features communicate their intent to navigate through their actions; this
/// reducer observes those actions and mutates `path` accordingly, keeping
/// navigation logic in one place.
@Reducer
struct AppFeature {
    /// The destinations that can be pushed onto the navigation stack. It describes every pushed screen.
    @Reducer
    enum Path {
        /// The detail screen for a single item.
        case detail(ItemDetailFeature)
    }

    /// The state of the root feature. It stores every pushed screen.
    @ObservableState
    struct State: Equatable {
        /// The state of the list screen, the root of the navigation stack.
        var list = ItemListFeature.State()

        /// The screens currently pushed on top of the list.
        var path = StackState<Path.State>()
    }

    /// The actions handled by the root feature.
    enum Action {
        /// Actions forwarded to the list screen.
        case list(ItemListFeature.Action)

        /// Actions forwarded to the screens on the navigation stack
        /// (including push / pop events).
        case path(StackActionOf<Path>)
    }

    var body: some ReducerOf<Self> {
        Scope(state: \.list, action: \.list) {
            ItemListFeature()
        }

        Reduce { state, action in
            switch action {
            case let .list(.delegate(.artistSelected(artist))):
                state.path.append(.detail(ItemDetailFeature.State(artist: artist)))
                return .none

            case .list:
                return .none

            case .path:
                return .none
            }
        }
        .forEach(\.path, action: \.path)
    }
}

/// `Path.State` is generated by `@Reducer`; it must be `Equatable` so that
/// ``AppFeature/State`` (which stores it in a `StackState`) can be `Equatable` too.
extension AppFeature.Path.State: Equatable {}
